export const resolveEstonianInlineText = (english: string): string => {
  const direct = TRANSLATIONS[english];
  if (direct) return direct;

  const minimum = english.match(/^Minimum length should be (\d+) characters\. You entered (\d+)\.$/);
  if (minimum) return `Minimaalne pikkus on ${minimum[1]} märki. Sisestasite ${minimum[2]}.`;

  const maximum = english.match(/^Maximum length should be (\d+) characters\. You entered (\d+)\.$/);
  if (maximum) return `Maksimaalne pikkus on ${maximum[1]} märki. Sisestasite ${maximum[2]}.`;

  const trustedAdd = english.match(/^Do you really want to add a trusted user (.+) \?$/);
  if (trustedAdd) return `Kas soovite lisada usaldatud kasutaja ${trustedAdd[1]}?`;

  const trustedReject = english.match(/^Do you really want to reject the request to add a trusted user (.+) \?$/);
  if (trustedReject) return `Kas soovite kasutaja ${trustedReject[1]} lisamise taotluse tagasi lükata?`;

  const trustedCancel = english.match(/^Do you really want to cancel the request to add a trusted user (.+) \?$/);
  if (trustedCancel) return `Kas soovite kasutaja ${trustedCancel[1]} lisamise taotluse tühistada?`;

  const legacyCancel = english.match(/^Are you sure you want to cancel your for (.+)\?$/);
  if (legacyCancel) return `Kas soovite taotluse kasutajale ${legacyCancel[1]} tühistada?`;

  return english;
};
